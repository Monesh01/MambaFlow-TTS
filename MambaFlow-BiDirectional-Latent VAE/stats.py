import numpy as np

LATENT_MIN_ARR = np.array(LATENT_MIN, dtype=np.float32)
LATENT_MAX_ARR = np.array(LATENT_MAX, dtype=np.float32)
LATENT_MEAN_ARR = np.array(LATENT_MEAN, dtype=np.float32)
LATENT_STD_ARR = np.array(LATENT_STD, dtype=np.float32)

def normalize_latent(x, mean_val=LATENT_MEAN_ARR, std_val=LATENT_STD_ARR):
    """
    Z-Score standardizes 128-dim latent to zero mean and unit variance.
    Supports both numpy arrays and torch Tensors of shapes [..., 128] or [..., 128, T].
    Formula: (x - mean) / (std + 1e-8)
    """
    try:
        import torch
        is_torch = isinstance(x, torch.Tensor)
    except ImportError:
        is_torch = False

    if is_torch:
        device, dtype = x.device, x.dtype
        mean_t = torch.as_tensor(mean_val, device=device, dtype=dtype)
        std_t = torch.as_tensor(std_val, device=device, dtype=dtype)
        if x.ndim == 3 and x.shape[1] == 128 and x.shape[2] != 128:
            mean_t = mean_t.view(1, 128, 1)
            std_t = std_t.view(1, 128, 1)
        elif x.ndim == 2 and x.shape[0] == 128 and x.shape[1] != 128:
            mean_t = mean_t.view(128, 1)
            std_t = std_t.view(128, 1)
        return (x - mean_t) / (std_t + 1e-8)
    else:
        mean_arr = np.asarray(mean_val, dtype=np.float32)
        std_arr = np.asarray(std_val, dtype=np.float32)
        if x.ndim == 3 and x.shape[1] == 128 and x.shape[2] != 128:
            mean_arr = mean_arr.reshape(1, 128, 1)
            std_arr = std_arr.reshape(1, 128, 1)
        elif x.ndim == 2 and x.shape[0] == 128 and x.shape[1] != 128:
            mean_arr = mean_arr.reshape(128, 1)
            std_arr = std_arr.reshape(128, 1)
        return (x - mean_arr) / (std_arr + 1e-8)

def denormalize_latent(x_norm, mean_val=LATENT_MEAN_ARR, std_val=LATENT_STD_ARR):
    """
    Inverts Z-Score standardization from standard space back to raw DACAE latent space.
    Supports both numpy arrays and torch Tensors of shapes [..., 128] or [..., 128, T].
    Formula: x_norm * std + mean
    """
    try:
        import torch
        is_torch = isinstance(x_norm, torch.Tensor)
    except ImportError:
        is_torch = False

    if is_torch:
        device, dtype = x_norm.device, x_norm.dtype
        mean_t = torch.as_tensor(mean_val, device=device, dtype=dtype)
        std_t = torch.as_tensor(std_val, device=device, dtype=dtype)
        if x_norm.ndim == 3 and x_norm.shape[1] == 128 and x_norm.shape[2] != 128:
            mean_t = mean_t.view(1, 128, 1)
            std_t = std_t.view(1, 128, 1)
        elif x_norm.ndim == 2 and x_norm.shape[0] == 128 and x_norm.shape[1] != 128:
            mean_t = mean_t.view(128, 1)
            std_t = std_t.view(128, 1)
        return x_norm * std_t + mean_t
    else:
        mean_arr = np.asarray(mean_val, dtype=np.float32)
        std_arr = np.asarray(std_val, dtype=np.float32)
        if x_norm.ndim == 3 and x_norm.shape[1] == 128 and x_norm.shape[2] != 128:
            mean_arr = mean_arr.reshape(1, 128, 1)
            std_arr = std_arr.reshape(1, 128, 1)
        elif x_norm.ndim == 2 and x_norm.shape[0] == 128 and x_norm.shape[1] != 128:
            mean_arr = mean_arr.reshape(128, 1)
            std_arr = std_arr.reshape(128, 1)
        return x_norm * std_arr + mean_arr

# Backward-compatibility alias for min-max
def normalize_latent_minmax(x, min_val=LATENT_MIN_ARR, max_val=LATENT_MAX_ARR):
    min_arr = np.asarray(min_val, dtype=np.float32)
    max_arr = np.asarray(max_val, dtype=np.float32)
    return 2.0 * (x - min_arr) / (max_arr - min_arr + 1e-8) - 1.0

def denormalize_latent_minmax(x_norm, min_val=LATENT_MIN_ARR, max_val=LATENT_MAX_ARR):
    min_arr = np.asarray(min_val, dtype=np.float32)
    max_arr = np.asarray(max_val, dtype=np.float32)
    return (x_norm + 1.0) * 0.5 * (max_arr - min_arr) + min_arr

